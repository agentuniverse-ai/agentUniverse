"""Prompt generation and optimization tool.

This module provides `PromptTool`, a utility that leverages an LLM component
to generate new prompts or optimize existing ones following the agentUniverse
prompt conventions (introduction / target / instruction with `{placeholder}`
input variables).

The tool is usable both programmatically and as a building block for
platform features:

    from agentuniverse.prompt.prompt_tool import PromptTool

    tool = PromptTool(llm_name='default_openai_llm')
    generated = tool.generate(scenario='customer service for an airline',
                              content='FAQ pages about baggage rules')
    print(generated.introduction, generated.target, generated.instruction)

    optimized = tool.optimize(introduction=..., target=..., instruction=...,
                              feedback='answers drift off topic')
"""

import json
import re
from typing import Any, List, Optional

from pydantic import BaseModel, Field

from agentuniverse.prompt.prompt_model import AgentPromptModel

GENERATE_SYSTEM_PROMPT = """You are an expert prompt engineer for the agentUniverse multi-agent framework.
agentUniverse composes agent prompts from three sections:
- introduction: the role and profile of the agent, who it is and what it knows.
- target: the goal the agent pursues, written as a concise mission statement.
- instruction: the concrete steps and constraints the agent follows, addressed to the agent itself.
Runtime values are referenced as {placeholder} variables inside the sections.
You answer with a single JSON object and nothing else."""

OPTIMIZE_SYSTEM_PROMPT = """You are an expert prompt engineer for the agentUniverse multi-agent framework.
You improve existing agent prompts (introduction / target / instruction sections,
{placeholder} input variables) by fixing ambiguity, missing context, weak
constraints and structural issues, while preserving the author's intent and
language. You answer with a single JSON object and nothing else."""

GENERATE_USER_TEMPLATE = """Generate the prompt of an agent for the following scenario.

Scenario: {scenario}
{target_block}{content_block}{language_block}
Return a JSON object with exactly these keys:
{{
  "introduction": "...",
  "target": "...",
  "instruction": "...",
  "input_variables": ["..."]
}}
Rules:
- Write each section as plain instructions addressed to the agent.
- Mark every runtime value in the sections as a {{placeholder}} and list it in
  input_variables, e.g. "user_question".
- Keep the sections focused; no JSON schema or markdown outside the object."""

OPTIMIZE_USER_TEMPLATE = """Optimize the following agent prompt.

Current introduction:
{introduction}

Current target:
{target}

Current instruction:
{instruction}
{feedback_block}{scenario_block}{language_block}
Return a JSON object with exactly these keys:
{{
  "introduction": "...",
  "target": "...",
  "instruction": "...",
  "input_variables": ["..."]
}}
Rules:
- Preserve the original intent and placeholders; add new {{placeholder}}
  variables only when they are clearly required.
- Keep the sections focused; no JSON schema or markdown outside the object."""


class GeneratedPrompt(BaseModel):
    """The result of a prompt generation or optimization run.

    Attributes:
        introduction (Optional[str]): The role and profile section.
        target (Optional[str]): The goal section.
        instruction (Optional[str]): The task instruction section.
        input_variables (List[str]): The `{placeholder}` variables used.
    """

    introduction: Optional[str] = None
    target: Optional[str] = None
    instruction: Optional[str] = None
    input_variables: List[str] = Field(default_factory=list)

    def as_agent_prompt_model(self) -> AgentPromptModel:
        """Convert to the AgentPromptModel consumed by agent prompts.

        Returns:
            The equivalent AgentPromptModel instance.
        """
        return AgentPromptModel(introduction=self.introduction,
                                target=self.target,
                                instruction=self.instruction)

    def to_yaml_config(self, name: str = 'generated_prompt',
                       description: str = 'prompt generated by PromptTool') -> str:
        """Render the component YAML configuration for this prompt.

        Args:
            name: The component name to write.
            description: The component description to write.

        Returns:
            A YAML string that can be saved into a project prompt directory.
        """
        def _block(section: Optional[str]) -> str:
            text = (section or '').strip()
            return text if text else ''

        lines = [
            f"name: '{name}'",
            f"description: '{description}'",
            "prompt_version: '1.0.0'",
            "metadata:",
            "  type: 'PROMPT'",
            "  module: 'agentuniverse.prompt.prompt'",
            "  class: 'Prompt'",
        ]
        for key in ('introduction', 'target', 'instruction'):
            value = _block(getattr(self, key))
            if value:
                lines.append(f"{key}: {json.dumps(value, ensure_ascii=False)}")
        if self.input_variables:
            variables = ', '.join(self.input_variables)
            lines.append(f"input_variables: [{variables}]")
        return '\n'.join(lines) + '\n'


class PromptTool:
    """LLM assisted prompt generation and optimization.

    Attributes:
        llm_name (str): The name of the registered LLM component used by
            the tool, e.g. `default_openai_llm`.
        llm (Any): An already built LLM instance; takes precedence over
            `llm_name` when provided, which keeps the tool easy to test
            and to embed.
        language (Optional[str]): The language the generated prompt should
            be written in, e.g. `English`, `中文`; unset means "follow the
            scenario language".
    """

    def __init__(self,
                 llm_name: str = 'default_openai_llm',
                 llm: Any = None,
                 language: Optional[str] = None):
        self.llm_name = llm_name
        self.llm = llm
        self.language = language

    def generate(self,
                 scenario: str,
                 content: Optional[str] = None,
                 target: Optional[str] = None) -> GeneratedPrompt:
        """Generate an agent prompt for a scenario.

        Args:
            scenario (str): What the agent is for, e.g. "customer service
                for an airline".
            content (Optional[str]): Reference material the prompt should
                build upon, e.g. FAQ pages, product docs.
            target (Optional[str]): An optional goal that overrides what
                the LLM infers from the scenario.

        Returns:
            The generated prompt sections and input variables.

        Raises:
            ValueError: If the scenario is empty or no LLM resolves.
        """
        user_prompt = self._build_generate_prompt(scenario, content, target)
        return self._run(user_prompt)

    def optimize(self,
                 introduction: str = '',
                 target: str = '',
                 instruction: str = '',
                 feedback: Optional[str] = None,
                 scenario: Optional[str] = None) -> GeneratedPrompt:
        """Optimize an existing agent prompt.

        Args:
            introduction (str): The current introduction section.
            target (str): The current target section.
            instruction (str): The current instruction section.
            feedback (Optional[str]): Problems to fix, e.g. "answers drift
                off topic"; the LLM also applies its own best practices.
            scenario (Optional[str]): The scenario the prompt serves, used
                as extra context.

        Returns:
            The optimized prompt sections and input variables.

        Raises:
            ValueError: If all sections are empty or no LLM resolves.
        """
        if not (introduction or target or instruction):
            raise ValueError("PromptTool.optimize: at least one of introduction, "
                             "target or instruction must be provided.")
        user_prompt = self._build_optimize_prompt(
            introduction=introduction, target=target, instruction=instruction,
            feedback=feedback, scenario=scenario)
        return self._run(user_prompt, system_prompt=OPTIMIZE_SYSTEM_PROMPT)

    async def agenerate(self, **kwargs) -> GeneratedPrompt:
        """Asynchronously generate an agent prompt, see `generate`."""
        return await self._arun(self._build_generate_prompt(**kwargs))

    async def aoptimize(self, **kwargs) -> GeneratedPrompt:
        """Asynchronously optimize an agent prompt, see `optimize`."""
        introduction = kwargs.get('introduction', '')
        target = kwargs.get('target', '')
        instruction = kwargs.get('instruction', '')
        if not (introduction or target or instruction):
            raise ValueError("PromptTool.aoptimize: at least one of introduction, "
                             "target or instruction must be provided.")
        return await self._arun(self._build_optimize_prompt(**kwargs),
                                system_prompt=OPTIMIZE_SYSTEM_PROMPT)

    def _build_generate_prompt(self, scenario: str, content: Optional[str] = None,
                               target: Optional[str] = None) -> str:
        if not scenario or not scenario.strip():
            raise ValueError("PromptTool.generate: scenario must be provided.")
        return GENERATE_USER_TEMPLATE.format(
            scenario=scenario.strip(),
            target_block=f"\nRequired target: {target.strip()}\n" if target else '',
            content_block=f"\nReference content:\n{content.strip()}\n" if content else '',
            language_block=f"\nWrite the prompt in {self.language}." if self.language else '',
        )

    def _build_optimize_prompt(self, introduction: str = '', target: str = '',
                               instruction: str = '', feedback: Optional[str] = None,
                               scenario: Optional[str] = None) -> str:
        return OPTIMIZE_USER_TEMPLATE.format(
            introduction=introduction or '(empty)',
            target=target or '(empty)',
            instruction=instruction or '(empty)',
            feedback_block=f"\nProblems to fix:\n{feedback.strip()}\n" if feedback else '',
            scenario_block=f"\nScenario the prompt serves: {scenario.strip()}\n" if scenario else '',
            language_block=f"\nWrite the prompt in {self.language}." if self.language else '',
        )

    def _get_llm(self):
        """Resolve the LLM instance to call.

        Returns:
            The provided llm instance or the registered component.

        Raises:
            ValueError: If no LLM instance resolves.
        """
        if self.llm is not None:
            return self.llm
        from agentuniverse.llm.llm_manager import LLMManager
        llm = LLMManager().get_instance_obj(self.llm_name)
        if llm is None:
            raise ValueError(
                f"PromptTool: llm '{self.llm_name}' not found. Register the "
                "LLM component or pass an llm instance directly.")
        return llm

    def _run(self, user_prompt: str,
             system_prompt: str = GENERATE_SYSTEM_PROMPT) -> GeneratedPrompt:
        """Call the LLM synchronously and parse its answer."""
        llm = self._get_llm()
        output = llm.call(messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ], streaming=False)
        text = getattr(output, 'text', '') or ''
        return self._parse(text)

    async def _arun(self, user_prompt: str,
                    system_prompt: str = GENERATE_SYSTEM_PROMPT) -> GeneratedPrompt:
        """Call the LLM asynchronously and parse its answer."""
        llm = self._get_llm()
        output = await llm.acall(messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ], streaming=False)
        text = getattr(output, 'text', '') or ''
        return self._parse(text)

    @staticmethod
    def _parse(text: str) -> GeneratedPrompt:
        """Parse the LLM answer into a GeneratedPrompt.

        Accepts raw JSON, fenced JSON and, as a last resort, the first
        balanced JSON object embedded in prose.

        Args:
            text: The LLM answer.

        Returns:
            The parsed prompt, with empty sections when nothing parses.

        Raises:
            ValueError: If the answer is empty.
        """
        if not text or not text.strip():
            raise ValueError("PromptTool: the LLM returned an empty answer.")

        candidate = PromptTool._extract_json(text)
        if candidate is None:
            return GeneratedPrompt()
        sections = {key: candidate.get(key) for key in
                    ('introduction', 'target', 'instruction')}
        input_variables = candidate.get('input_variables') or []
        if not isinstance(input_variables, list):
            input_variables = [str(input_variables)]
        return GeneratedPrompt(
            **{key: value for key, value in sections.items() if isinstance(value, str)},
            input_variables=[str(variable) for variable in input_variables],
        )

    @staticmethod
    def _extract_json(text: str) -> Optional[dict]:
        """Extract the first JSON object found in the text.

        Args:
            text: The text to scan.

        Returns:
            The parsed dict, or None when no valid object is found.
        """
        cleaned = text.strip()
        fenced = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", cleaned, re.S)
        if fenced:
            cleaned = fenced.group(1)
        start = cleaned.find('{')
        while start != -1:
            depth = 0
            in_string = False
            escaped = False
            for index in range(start, len(cleaned)):
                char = cleaned[index]
                if in_string:
                    if escaped:
                        escaped = False
                    elif char == '\\':
                        escaped = True
                    elif char == '"':
                        in_string = False
                    continue
                if char == '"':
                    in_string = True
                elif char == '{':
                    depth += 1
                elif char == '}':
                    depth -= 1
                    if depth == 0:
                        try:
                            parsed = json.loads(cleaned[start:index + 1])
                            if isinstance(parsed, dict):
                                return parsed
                        except json.JSONDecodeError:
                            pass
                        break
            start = cleaned.find('{', start + 1)
        return None
