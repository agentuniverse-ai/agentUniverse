"""Shannon entropy: deterministic known-answer vectors (auext)."""

import math

def _ref_entropy_bits(case):
    """Shannon entropy in bits of an integer count distribution.

    Zero-count bins are skipped; a zero total yields 0.0.
    """
    counts = case
    total = 0
    for c in counts:
        total += c
    if total <= 0:
        return 0.0
    e = 0.0
    for c in counts:
        if c > 0:
            p = c / total
            e -= p * math.log2(p)
    return round(e, 6)

