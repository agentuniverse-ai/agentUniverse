"""Nullable JSON integers must survive an unsuccessful earlier anyOf branch.

The nullable schema is generated by actual Pydantic, and the request cases use
real APITool execution and HTTPX JSON-body serialization. Only HTTP transport is
replaced with an in-process MockTransport; there is no external HTTP endpoint.
"""
import json
from copy import deepcopy
from typing import Optional

import httpx
import pytest
from pydantic import BaseModel

from agentuniverse.agent.action.tool.api_tool import APITool
from agentuniverse.agent.action.tool.tool import ToolInput
from agentuniverse.agent.action.tool.utils import ssrf_proxy


class NullableRequest(BaseModel):
    count: Optional[int]


@pytest.mark.parametrize("depth", [0, 1, 2])
def test_nullable_integer_reaches_null_branch_after_integer_rejection(depth):
    schema = NullableRequest.model_json_schema()["properties"]["count"]
    assert schema["anyOf"] == [{"type": "integer"}, {"type": "null"}]
    for _ in range(depth):
        schema = {"anyOf": [schema, {"type": "string"}]}
    before = deepcopy(schema)

    assert APITool().convert_body_property_type(schema, None) is None
    assert schema == before


@pytest.mark.parametrize("method", ["post", "put"])
@pytest.mark.parametrize("value", [None, 0, 7])
def test_execute_serializes_supported_nullable_integer_request(monkeypatch, method, value):
    # The actual model accepts all these values; this is not an invalid-input
    # fallback requirement introduced by the test.
    validated = NullableRequest(count=value)
    payload = validated.model_dump()
    body_schema = NullableRequest.model_json_schema()
    spec = {
        "url": "https://unit.invalid/nullable",
        "method": method,
        "operation": {"parameters": []},
        "requestBody": {
            "content": {"application/json": {"schema": body_schema}},
        },
    }
    before = deepcopy(spec)
    received = []

    def handle(request):
        assert request.method == method.upper()
        assert request.headers["Content-Type"] == "application/json"
        received.append(json.loads(request.content))
        return httpx.Response(200, json={"received": received[-1]})

    tool = APITool(openapi_spec=spec)
    with httpx.Client(transport=httpx.MockTransport(handle)) as client:
        monkeypatch.setattr(ssrf_proxy, method, getattr(client, method))
        response_text = tool.execute(ToolInput(payload))

    assert received == [{"count": value}]
    assert json.loads(response_text) == {"received": {"count": value}}
    assert payload == {"count": value}
    assert tool.openapi_spec == before


@pytest.mark.parametrize("value,expected", [("12", 12), (12, 12), ("keep", "keep")])
def test_existing_integer_conversion_and_unmatched_fallback_are_unchanged(value, expected):
    schema = NullableRequest.model_json_schema()["properties"]["count"]
    result = APITool().convert_body_property_type(schema, value)
    assert result == expected
    assert type(result) is type(expected)


def test_existing_null_first_schema_still_returns_none():
    schema = {"anyOf": [{"type": "null"}, {"type": "integer"}]}
    assert APITool().convert_body_property_type(schema, None) is None


def test_direct_nonnullable_integer_error_is_not_suppressed():
    with pytest.raises(TypeError):
        APITool().convert_body_property_type({"type": "integer"}, None)
