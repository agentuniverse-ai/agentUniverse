"""Levenshtein edit distance: deterministic known-answer vectors (auext)."""

def _ref_levenshtein(case):
    """Classic Levenshtein edit distance with insertion, deletion, substitution.

    ``case`` is a pair of strings; the result counts the minimum number of
    single-character edits needed to turn the first string into the second.
    """
    a, b = case
    la, lb = len(a), len(b)
    prev = list(range(lb + 1))
    for i in range(1, la + 1):
        cur = [i] + [0] * lb
        for j in range(1, lb + 1):
            cost = 0 if a[i - 1] == b[j - 1] else 1
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost)
        prev = cur
    return prev[lb]

