"""Dotted-quad parsing: deterministic known-answer vectors (auext)."""

def _ref_ipv4_octets(case):
    """Parse a dotted-quad address into four octets, or [] when invalid.

    Leading zeros are rejected in runs longer than one digit.
    """
    parts = case.split(".")
    if len(parts) != 4:
        return []
    out = []
    for p in parts:
        if not p:
            return []
        for ch in p:
            if ch < "0" or ch > "9":
                return []
        if len(p) > 1 and p[0] == "0":
            return []
        v = int(p)
        if v > 255:
            return []
        out.append(v)
    return out

