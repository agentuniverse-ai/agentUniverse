    """FNV-1a 64-bit hash of the UTF-8 encoding of a string."""
    h = 0xCBF29CE484222325
    for b in case.encode("utf-8"):
        h = (h ^ b) & 0xFFFFFFFFFFFFFFFF
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h

