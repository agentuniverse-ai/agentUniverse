"""Polynomial rolling hash: deterministic known-answer vectors (auext)."""

def _ref_rolling_hash(case):
    """Polynomial rolling hash: h = (h*base + byte) mod modulus.

    Returns -1 when the base or modulus is not positive.
    """
    s, base, mod = case
    if base <= 0 or mod <= 0:
        return -1
    h = 0
    for b in s.encode("utf-8"):
        h = (h * base + b) % mod
    return h

