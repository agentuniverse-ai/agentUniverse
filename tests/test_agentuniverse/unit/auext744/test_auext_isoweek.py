import datetime

def _ref_iso_week(case):
    """ISO week of a date as [year, week, weekday]; [0,0,0] when invalid."""
    y, m, d = case
    try:
        dt = datetime.date(y, m, d)
    except ValueError:
        return [0, 0, 0]
    wy, ww, wd = dt.isocalendar()
    return [wy, ww, wd]

