"""Gini coefficient: deterministic known-answer vectors (auext)."""

def _ref_gini(case):
    """Gini coefficient of a value list: 0 for equality, near 1 for concentration.

    Sorting is ascending; the 1/n weighting makes scales comparable.
    """
    vals = case
    n = len(vals)
    if n == 0:
        return 0.0
    sv = sorted(vals)
    total = 0
    for v in sv:
        total += v
    if total == 0:
        return 0.0
    num = 0.0
    for i, v in enumerate(sv, 1):
        num += (2 * i - n - 1) * v
    return round(num / (n * total), 6)

