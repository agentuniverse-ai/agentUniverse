"""Caesar shift: deterministic known-answer vectors (auext)."""

def _ref_caesar(case):
    """Shift letters of a string by ``k`` positions, preserving case.

    Non-letters pass through; negative and oversized shifts are reduced mod 26.
    """
    s, k = case
    shift = ((k % 26) + 26) % 26
    out = []
    for ch in s:
        if "a" <= ch <= "z":
            out.append(chr((ord(ch) - 97 + shift) % 26 + 97))
        elif "A" <= ch <= "Z":
            out.append(chr((ord(ch) - 65 + shift) % 26 + 65))
        else:
            out.append(ch)
    return "".join(out)

