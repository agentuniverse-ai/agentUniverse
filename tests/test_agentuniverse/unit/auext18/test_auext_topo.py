"""Kahn topological sort: deterministic known-answer vectors (auext)."""

def _ref_topo_sort(case):
    """Kahn topological order over nodes 0..n-1 with insertion-order choices.

    Returns the order, or [] when the graph contains a cycle.
    """
    n, edges = case
    adj = [[] for _ in range(n)]
    indeg = [0] * n
    for u, v in edges:
        if 0 <= u < n and 0 <= v < n:
            adj[u].append(v)
            indeg[v] += 1
    order = []
    ready = [i for i in range(n) if indeg[i] == 0]
    while ready:
        x = ready.pop(0)
        order.append(x)
        for v in adj[x]:
            indeg[v] -= 1
            if indeg[v] == 0:
                ready.append(v)
    if len(order) != n:
        return []
    return order

