"""Precision at k: deterministic known-answer vectors (auext)."""

def _ref_precision_at_k(case):
    """Precision at k: relevant hits among the first k, divided by k."""
    rels, k = case
    if k <= 0:
        return 0.0
    hits = 0
    for r in rels[:k]:
        if r:
            hits += 1
    return round(hits / k, 6)

