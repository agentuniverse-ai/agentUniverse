def _ref_welford(case):
    """Online mean and sample variance via Welford; variance 0.0 for n < 2.

    Returns [mean, variance] with both rounded to 6 decimals.
    """
    count = 0
    mean = 0.0
    m2 = 0.0
    for x in case:
        count += 1
        delta = x - mean
        mean += delta / count
        m2 += delta * (x - mean)
    var = 0.0 if count < 2 else m2 / (count - 1)
    return [round(mean, 6), round(var, 6)]

