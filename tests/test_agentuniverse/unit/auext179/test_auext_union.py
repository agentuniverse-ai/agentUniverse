"""Union-find component count: deterministic known-answer vectors (auext)."""

def _ref_union_count(case):
    """Count connected components of an undirected graph via union-find.

    Edges outside the node range are ignored; isolated nodes count alone.
    """
    n, edges = case
    parent = list(range(n))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for u, v in edges:
        if 0 <= u < n and 0 <= v < n:
            pu = find(u)
            pv = find(v)
            if pu != pv:
                parent[pu] = pv
    count = 0
    for i in range(n):
        if find(i) == i:
            count += 1
    return count

