def _ref_jaccard(case):
    """Jaccard similarity of the token sets of two lists, 1.0 when both empty."""
    a, b = case
    sa = set(a)
    sb = set(b)
    union = sa | sb
    if not union:
        return 1.0
    return round(len(sa & sb) / len(union), 6)

