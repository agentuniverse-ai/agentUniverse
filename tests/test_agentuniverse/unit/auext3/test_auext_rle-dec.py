"""Run-length decoding: deterministic known-answer vectors (auext)."""

def _ref_rle_decode(case):
    """Expand (char, count) pairs back into a string.

    Non-positive counts contribute nothing; the result may be empty.
    """
    out = []
    for ch, count in case:
        if len(ch) == 1 and count > 0:
            out.append(ch * count)
    return "".join(out)

