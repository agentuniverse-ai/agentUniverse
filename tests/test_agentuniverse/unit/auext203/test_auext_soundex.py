"""Simplified Soundex: deterministic known-answer vectors (auext)."""

def _ref_soundex(case):
    """Simplified Soundex: first letter kept, then consonant codes, 4 chars.

    Vowel codes (A E I O U Y) reset the previous-code memory; H and W are
    ignored. Non-letters are skipped. Output is padded with zeros to length 4.
    """
    word = case
    if not word:
        return ""
    word = word.upper()
    if not ("A" <= word[0] <= "Z"):
        return ""
    codes = "01230120022455012623010202"
    out = word[0]
    last = codes[ord(word[0]) - 65]
    for ch in word[1:]:
        if not ("A" <= ch <= "Z"):
            continue
        c = codes[ord(ch) - 65]
        if c == "0":
            if ch in "AEIOUY":
                last = "0"
            continue
        if c != last:
            out += c
        last = c
    return (out + "000")[:4]

