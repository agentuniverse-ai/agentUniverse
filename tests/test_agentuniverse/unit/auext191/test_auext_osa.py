"""Optimal string alignment distance: deterministic known-answer vectors (auext)."""

def _ref_osa(case):
    """Optimal string alignment distance (restricted Damerau-Levenshtein).

    Besides insert, delete and substitute, an adjacent transposition of two
    characters counts as a single edit. No further edits after a transposition.
    """
    a, b = case
    la, lb = len(a), len(b)
    d = [[0] * (lb + 1) for _ in range(la + 1)]
    for i in range(la + 1):
        d[i][0] = i
    for j in range(lb + 1):
        d[0][j] = j
    for i in range(1, la + 1):
        for j in range(1, lb + 1):
            cost = 0 if a[i - 1] == b[j - 1] else 1
            best = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + cost)
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                best = min(best, d[i - 2][j - 2] + 1)
            d[i][j] = best
    return d[la][lb]

