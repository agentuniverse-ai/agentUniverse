"""Exponential backoff schedule: deterministic known-answer vectors (auext)."""

def _ref_backoff_sched(case):
    """Exponential backoff: base * 2**i capped at cap, one delay per round.

    Base and cap are positive integers; the cap guarantees termination.
    """
    n, base, cap = case
    if n <= 0:
        return []
    out = []
    for i in range(n):
        delay = base * (2 ** i)
        if delay > cap:
            delay = cap
        out.append(delay)
    return out

