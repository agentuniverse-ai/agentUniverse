"""Hamming distance: deterministic known-answer vectors (auext)."""

def _ref_hamming(case):
    """Hamming distance of two equal-length strings, or -1 when lengths differ.

    Returns the number of differing positions; equal strings yield 0.
    """
    a, b = case
    if len(a) != len(b):
        return -1
    total = 0
    for x, y in zip(a, b):
        if x != y:
            total += 1
    return total

