"""Mean reciprocal rank: deterministic known-answer vectors (auext)."""

def _ref_mrr(case):
    """Mean reciprocal rank over rows of 0/1 relevance marks.

    Rows without any relevant item contribute zero; an empty row set is 0.0.
    """
    rows = case
    if not rows:
        return 0.0
    total = 0.0
    for row in rows:
        rr = 0.0
        for i, r in enumerate(row):
            if r:
                rr = 1.0 / (i + 1)
                break
        total += rr
    return round(total / len(rows), 6)

