"""LRU trace accounting: deterministic known-answer vectors (auext)."""

def _ref_lru_trace(case):
    """Least-recently-used trace: counts hits, misses and evictions.

    The cache starts empty; each touched key moves to the most recent slot and
    overflow evicts exactly one least-recent key.
    """
    cap, keys = case
    if cap <= 0:
        return [0, len(keys), 0]
    seen = []
    hits = 0
    misses = 0
    evictions = 0
    for k in keys:
        if k in seen:
            hits += 1
            seen.remove(k)
            seen.insert(0, k)
        else:
            misses += 1
            seen.insert(0, k)
            if len(seen) > cap:
                seen.pop()
                evictions += 1
    return [hits, misses, evictions]

