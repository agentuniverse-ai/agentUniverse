def _ref_trimmed_mean(case):
    """Arithmetic mean after discarding ``trim`` of the values on each side.

    The trim fraction is applied to the count, floored; extremes of the sorted
    copy are ignored symmetrically.
    """
    xs, trim = case
    if not xs:
        return 0.0
    n = len(xs)
    k = int(n * trim)
    if 2 * k >= n:
        k = (n - 1) // 2
    sv = sorted(xs)
    keep = sv[k:n - k]
    if not keep:
        return 0.0
    total = 0.0
    for v in keep:
        total += v
    return round(total / len(keep), 6)

