"""Base 36 encoding: deterministic known-answer vectors (auext)."""

def _ref_base36(case):
    """Encode a non-negative or negative integer in lower-case base 36.

    Zero encodes to "0"; the sign, if any, becomes a leading minus.
    """
    n = case
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    if n == 0:
        return "0"
    sign = ""
    if n < 0:
        sign = "-"
        n = -n
    out = []
    while n:
        out.append(digits[n % 36])
        n = n // 36
    return sign + "".join(reversed(out))

