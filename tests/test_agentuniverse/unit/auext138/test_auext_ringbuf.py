"""Evicting ring buffer: deterministic known-answer vectors (auext)."""

def _ref_ring_buf(case):
    """Ring buffer: pushing into a full ring evicts the oldest and reports it.

    A successful push yields None when nothing was evicted; pops yield the
    removed value or None when the ring is empty.
    """
    cap, ops = case
    items = []
    out = []
    for op, x in ops:
        if op == 1:
            if cap <= 0:
                out.append(x)
                continue
            if len(items) == cap:
                out.append(items.pop(0))
            else:
                out.append(None)
            items.append(x)
        else:
            if items:
                out.append(items.pop(0))
            else:
                out.append(None)
    return out

