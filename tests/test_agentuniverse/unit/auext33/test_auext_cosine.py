"""Cosine similarity of counts: deterministic known-answer vectors (auext)."""

import math

def _ref_cosine_counts(case):
    """Cosine similarity of two count dictionaries, rounded to 6 decimals.

    A missing term counts as zero; either empty dictionary yields 0.0.
    """
    a, b = case
    if not a or not b:
        return 0.0
    num = 0
    for t, v in a.items():
        num += v * b.get(t, 0)
    da = 0.0
    for v in a.values():
        da += v * v
    db = 0.0
    for v in b.values():
        db += v * v
    if da == 0 or db == 0:
        return 0.0
    return round(num / (math.sqrt(da) * math.sqrt(db)), 6)

