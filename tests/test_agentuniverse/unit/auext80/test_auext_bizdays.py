"""Business-day arithmetic: deterministic known-answer vectors (auext)."""

import datetime

def _ref_add_biz_days(case):
    """Date plus k business days, skipping Saturdays and Sundays.

    Returns the result as YYYY-MM-DD; invalid dates yield "invalid".
    """
    y, m, d, k = case
    try:
        cur = datetime.date(y, m, d) + datetime.timedelta(days=k)
    except (ValueError, OverflowError):
        return "invalid"
    while cur.weekday() >= 5:
        cur = cur + datetime.timedelta(days=1)
    return cur.strftime("%Y-%m-%d")

