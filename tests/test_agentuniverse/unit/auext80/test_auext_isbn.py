"""ISBN-10 check digit: deterministic known-answer vectors (auext)."""

def _ref_isbn10(case):
    """ISBN-10 validation; dashes and spaces ignored, trailing X counts as 10.

    The weighted sum (10-i) * digit must vanish modulo 11.
    """
    t = case.replace("-", "").replace(" ", "")
    if len(t) != 10:
        return False
    total = 0
    for i, ch in enumerate(t):
        if "0" <= ch <= "9":
            v = ord(ch) - 48
        elif ch == "X" and i == 9:
            v = 10
        else:
            return False
        total += v * (10 - i)
    return total % 11 == 0

