"""INI config parser: deterministic known-answer vectors (auext)."""

def _ref_ini_parse(case):
    """Parse INI text: [sections], key=value, full-line # or ; comments.

    Lines before any section land in "_root"; later keys overwrite earlier
    ones; quoted values lose their matching outer quotes.
    """
    out = {}
    cur = "_root"
    for raw in case.split("\n"):
        s = raw.strip()
        if not s or s[0] in "#;":
            continue
        if s[0] == "[" and "]" in s:
            cur = s[1:s.index("]")].strip()
            if cur not in out:
                out[cur] = {}
            continue
        if "=" not in s:
            continue
        key, _, val = s.partition("=")
        key = key.strip()
        if not key:
            continue
        val = val.strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "'\"":
            val = val[1:-1]
        if cur not in out:
            out[cur] = {}
        out[cur][key] = val
    return out

