"""Underscores to dashes: deterministic known-answer vectors (auext)."""

def _ref_to_kebab(case):
    """Lowercase a name, collapse underscore runs and join words with dashes."""
    s = case.lower()
    while "__" in s:
        s = s.replace("__", "-")
    return s.replace("_", "-")

