"""Dotenv parser: deterministic known-answer vectors (auext)."""

def _ref_env_parse(case):
    """Parse dotenv-style text with export prefixes and # comments.

    Later assignments overwrite earlier ones; unquoted values drop an inline
    comment; quoted values keep their inner text.
    """
    out = {}
    for raw in case.split("\n"):
        s = raw.strip()
        if not s or s[0] == "#":
            continue
        if s.startswith("export "):
            s = s[7:].strip()
        if "=" not in s:
            continue
        key, _, val = s.partition("=")
        key = key.strip()
        if not key:
            continue
        bad = False
        for ch in key:
            if not ("A" <= ch <= "Z" or "a" <= ch <= "z" or "0" <= ch <= "9" or ch in "_."):
                bad = True
        if bad:
            continue
        val = val.strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "'\"":
            val = val[1:-1]
        else:
            if "#" in val:
                val = val.split("#")[0].strip()
        out[key] = val
    return out

