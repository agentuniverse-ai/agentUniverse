"""BM25 scoring: deterministic known-answer vectors (auext)."""

import math

def _ref_bm25(case):
    """BM25 score of one document for a query, rounded to 6 decimals.

    ``case`` = (query terms, document terms, document frequencies, corpus size,
    average document length, k1, b). Missing terms use document frequency 0.
    """
    query, doc, df, n_docs, avgdl, k1, b = case
    if not doc or avgdl <= 0:
        return 0.0
    dl = len(doc)
    score = 0.0
    for term in query:
        tf = doc.count(term)
        if tf == 0:
            continue
        nq = df.get(term, 0)
        idf = math.log((n_docs - nq + 0.5) / (nq + 0.5) + 1.0)
        score += idf * tf * (k1 + 1) / (tf + k1 * (1 - b + b * dl / avgdl))
    return round(score, 6)

