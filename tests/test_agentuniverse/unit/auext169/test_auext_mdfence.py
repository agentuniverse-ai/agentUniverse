"""Markdown fence extraction: deterministic known-answer vectors (auext)."""

def _ref_md_fences(case):
    """Extract fenced code blocks from Markdown.

    A line starting with ``` toggles the fenced state; the collected content of
    each fenced region is joined with newlines; unterminated fences are kept.
    """
    blocks = []
    inside = False
    cur = []
    for line in case.split("\n"):
        if line.startswith("```"):
            if inside:
                blocks.append("\n".join(cur))
                cur = []
                inside = False
            else:
                inside = True
        elif inside:
            cur.append(line)
    if inside and cur:
        blocks.append("\n".join(cur))
    return blocks

