"""Bounded FIFO buffer: deterministic known-answer vectors (auext)."""

def _ref_leaky_buf(case):
    """Bounded FIFO: push (1, x) drops the oldest when full; pop (2, 0) yields.

    Pops from the empty queue yield None; pushes produce no output.
    """
    cap, ops = case
    items = []
    out = []
    for op, x in ops:
        if op == 1:
            if cap > 0 and len(items) == cap:
                items.pop(0)
            if cap > 0:
                items.append(x)
        else:
            if items:
                out.append(items.pop(0))
            else:
                out.append(None)
    return out

