def _ref_ngrams(case):
    """Character n-grams of a text in left-to-right order.

    Returns an empty list when the gram length exceeds the text length.
    """
    text, n = case
    if n <= 0 or n > len(text):
        return []
    return [text[i:i + n] for i in range(len(text) - n + 1)]

