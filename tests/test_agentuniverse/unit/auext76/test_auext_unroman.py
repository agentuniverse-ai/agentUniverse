"""Int to Roman numerals: deterministic known-answer vectors (auext)."""

def _ref_int_to_roman(case):
    """Render 1..3999 as a Roman numeral; other integers give the empty string."""
    n = case
    if n <= 0 or n > 3999:
        return ""
    pairs = [(1000, "M"), (900, "CM"), (500, "D"), (400, "CD"), (100, "C"),
             (90, "XC"), (50, "L"), (40, "XL"), (10, "X"), (9, "IX"),
             (5, "V"), (4, "IV"), (1, "I")]
    out = []
    for value, sym in pairs:
        while n >= value:
            out.append(sym)
            n -= value
    return "".join(out)

