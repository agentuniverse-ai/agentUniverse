"""Jaro similarity: deterministic known-answer vectors (auext)."""

def _ref_jaro(case):
    """Jaro similarity of two strings, rounded to 6 decimals.

    Characters within a match window are paired greedily; the score mixes the
    match ratio of both sides with the halved transposition ratio.
    """
    s1, s2 = case
    if not s1 and not s2:
        return 1.0
    if not s1 or not s2:
        return 0.0
    window = max(len(s1), len(s2)) // 2 - 1
    if window < 0:
        window = 0
    m1 = [False] * len(s1)
    m2 = [False] * len(s2)
    matched = 0
    for i, ch in enumerate(s1):
        lo = i - window
        if lo < 0:
            lo = 0
        hi = i + window + 1
        if hi > len(s2):
            hi = len(s2)
        for j in range(lo, hi):
            if not m2[j] and s2[j] == ch:
                m1[i] = True
                m2[j] = True
                matched += 1
                break
    if matched == 0:
        return 0.0
    k = 0
    trans = 0
    for i in range(len(s1)):
        if m1[i]:
            while not m2[k]:
                k += 1
            if s1[i] != s2[k]:
                trans += 1
            k += 1
    trans = trans // 2
    return round((matched / len(s1) + matched / len(s2) + (matched - trans) / matched) / 3.0, 6)

