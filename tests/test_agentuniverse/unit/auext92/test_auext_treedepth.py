"""Tree depth by BFS: deterministic known-answer vectors (auext)."""

def _ref_tree_depth(case):
    """Depth of an undirected tree from its root by BFS; -1 on a bad root.

    The depth counts edges on the longest path; a lone root yields 0.
    """
    n, edges, root = case
    if not 0 <= root < n:
        return -1
    adj = [[] for _ in range(n)]
    for u, v in edges:
        if 0 <= u < n and 0 <= v < n:
            adj[u].append(v)
            adj[v].append(u)
    visited = {root}
    frontier = [root]
    depth = -1
    while frontier:
        depth += 1
        nxt = []
        for x in frontier:
            for v in adj[x]:
                if v not in visited:
                    visited.add(v)
                    nxt.append(v)
        frontier = nxt
    return depth

