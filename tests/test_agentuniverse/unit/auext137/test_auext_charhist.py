"""Character histogram: deterministic known-answer vectors (auext)."""

def _ref_charhist(case):
    """Histogram of characters mapped to occurrence counts.

    Keys appear in first-occurrence order; comparison ignores that order.
    """
    counts = {}
    for ch in case:
        counts[ch] = counts.get(ch, 0) + 1
    return counts

