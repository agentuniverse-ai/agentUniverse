"""Luhn checksum: deterministic known-answer vectors (auext)."""

def _ref_luhn(case):
    """Luhn checksum validation of a digit string; spaces are ignored.

    Doubled digits beyond nine contribute their digit sum; non-digits or an
    empty payload fail.
    """
    digits = case.replace(" ", "")
    if not digits:
        return False
    for ch in digits:
        if ch < "0" or ch > "9":
            return False
    vals = [int(c) for c in digits]
    vals.reverse()
    total = 0
    for i, v in enumerate(vals):
        if i % 2 == 1:
            v = v * 2
            if v > 9:
                v = v - 9
        total += v
    return total % 10 == 0

