def _ref_camel_to_snake(case):
    """Convert a CamelCase identifier to lower_snake_case.

    An underscore is inserted before an uppercase letter that follows a lowercase
    letter or ends an uppercase run, as in "HTTPServer2" -> "http_server2".
    """
    s = case
    out = []
    for i, ch in enumerate(s):
        if "A" <= ch <= "Z" and i > 0:
            prev = s[i - 1]
            nxt = s[i + 1] if i + 1 < len(s) else ""
            upper_run = "A" <= prev <= "Z"
            if (not upper_run) or (nxt and "a" <= nxt <= "z"):
                out.append("_")
        if "A" <= ch <= "Z":
            out.append(ch.lower())
        else:
            out.append(ch)
    return "".join(out)

