"""Run-length encoding: deterministic known-answer vectors (auext)."""

def _ref_rle_encode(case):
    """Run-length encode a string as (char, count) pairs."""
    s = case
    if not s:
        return []
    out = []
    cur = s[0]
    run = 1
    for ch in s[1:]:
        if ch == cur:
            run += 1
        else:
            out.append((cur, run))
            cur = ch
            run = 1
    out.append((cur, run))
    return out

