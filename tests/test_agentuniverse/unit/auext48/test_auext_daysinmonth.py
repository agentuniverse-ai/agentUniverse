import calendar

def _ref_days_in_month(case):
    """Days in a month of the proleptic Gregorian calendar; 0 when invalid."""
    y, m = case
    if y < 1 or m < 1 or m > 12:
        return 0
    return calendar.monthrange(y, m)[1]

