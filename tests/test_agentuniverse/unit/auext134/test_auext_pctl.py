"""Linear percentile: deterministic known-answer vectors (auext)."""

def _ref_percentile(case):
    """Linear-interpolated percentile of a list, 0..100.

    Values below 0 clamp to the minimum, above 100 to the maximum; the empty
    list yields 0.0.
    """
    xs, p = case
    if not xs:
        return 0.0
    sv = sorted(xs)
    if p <= 0:
        return round(float(sv[0]), 6)
    if p >= 100:
        return round(float(sv[-1]), 6)
    r = (len(sv) - 1) * p / 100.0
    lo = int(r)
    hi = lo + 1
    if hi > len(sv) - 1:
        hi = len(sv) - 1
    frac = r - lo
    return round(float(sv[lo]) + (sv[hi] - sv[lo]) * frac, 6)

