"""Normalized discounted cumulative gain: deterministic known-answer vectors (auext)."""

import math

def _ref_ndcg(case):
    """Normalized discounted cumulative gain with gains 0..3.

    Uses the supplied ideal ranking; a zero-ideal yields 0.0.
    """
    gains, k, ideal = case

    def dcg(values, kk):
        total = 0.0
        for i, v in enumerate(values[:kk]):
            if v > 0:
                total += (2.0 ** v - 1) / math.log2(i + 2)
        return total

    idcg = dcg(ideal, k)
    if idcg == 0:
        return 0.0
    return round(dcg(gains, k) / idcg, 6)

