def _ref_mask_secret(case):
    """Mask a secret, keeping the last ``keep`` characters.

    Short secrets and non-positive keeps are returned unchanged; longer ones
    become four stars followed by the retained suffix.
    """
    s, keep = case
    if not s:
        return ""
    if keep <= 0:
        return "****"
    if len(s) <= keep:
        return s
    return "****" + s[-keep:]

