"""Roman numerals to int: deterministic known-answer vectors (auext)."""

def _ref_roman_to_int(case):
    """Parse a Roman numeral; -1 when an unknown symbol appears.

    Subtractive notation is handled by comparing each value with its successor.
    """
    vals = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100, "D": 500, "M": 1000}
    s = case
    if not s:
        return 0
    for ch in s:
        if ch not in vals:
            return -1
    total = 0
    for i, ch in enumerate(s):
        v = vals[ch]
        if i + 1 < len(s) and v < vals[s[i + 1]]:
            total -= v
        else:
            total += v
    return total

