"""Base 36 decoding: deterministic known-answer vectors (auext)."""

def _ref_unbase36(case):
    """Decode a base 36 string; -1 on any unexpected character.

    Surrounding whitespace makes the input invalid; the empty string is 0.
    """
    s = case
    if s == "":
        return 0
    if s != s.strip():
        return -1
    total = 0
    for ch in s.lower():
        if "0" <= ch <= "9":
            total = total * 36 + (ord(ch) - 48)
        elif "a" <= ch <= "z":
            total = total * 36 + (ord(ch) - 87)
        else:
            return -1
    return total

