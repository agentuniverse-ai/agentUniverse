"""IBAN mod-97 check: deterministic known-answer vectors (auext)."""

def _ref_iban_check(case):
    """IBAN mod-97 validation of a spaced or plain code.

    Requires 15..34 characters, two country letters, two check digits, and a
    rearranged numeric form congruent to 1 modulo 97.
    """
    t = case.replace(" ", "").upper()
    if len(t) < 15 or len(t) > 34:
        return False
    for ch in t[:2]:
        if not ("A" <= ch <= "Z"):
            return False
    for ch in t[2:4]:
        if ch < "0" or ch > "9":
            return False
    rearr = t[4:] + t[:4]
    num = ""
    for ch in rearr:
        if "0" <= ch <= "9":
            num += ch
        elif "A" <= ch <= "Z":
            num += str(ord(ch) - 55)
        else:
            return False
    return int(num) % 97 == 1

