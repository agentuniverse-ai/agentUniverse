"""Reciprocal rank fusion: deterministic known-answer vectors (auext)."""

def _ref_rrf(case):
    """Reciprocal rank fusion over ranked lists with the usual k=60.

    Returns (doc, score) pairs sorted by decreasing score, ties by doc id.
    """
    lists = case
    scores = {}
    for ranked in lists:
        for i, doc in enumerate(ranked):
            scores[doc] = scores.get(doc, 0.0) + 1.0 / (60 + i + 1)
    order = sorted(scores, key=lambda d: (-scores[d], d))
    return [(d, round(scores[d], 6)) for d in order]

